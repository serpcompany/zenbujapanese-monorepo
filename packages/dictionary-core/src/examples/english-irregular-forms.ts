function basesByForm(basesWithTheirForms: readonly string[]): ReadonlyMap<string, string> {
  return new Map(
    basesWithTheirForms.flatMap(row => {
      const [base, ...forms] = row.split(' ')
      return forms.map((form): [string, string] => [form, base])
    })
  )
}

